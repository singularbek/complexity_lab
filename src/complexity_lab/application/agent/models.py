"""Data models and schemas for the Scientific Agent."""

from typing import Any

from pydantic import BaseModel, Field


class Hypothesis(BaseModel):
    """Scientific hypothesis formulated by the agent."""

    statement: str = Field(..., description="The scientific question or prediction being tested")
    reasoning: str = Field(..., description="Theoretical background or motivation")
    expected_outcome: str = Field(..., description="Expected observable behavior or transition")


class PlannedExperiment(BaseModel):
    """Specification of a single experiment within a research plan."""

    experiment_name: str = Field(..., description="Descriptive label for this run")
    simulation_type: str = Field(default="cellular_automaton", description="Simulation identifier")
    parameters: dict[str, Any] = Field(default_factory=dict, description="Simulation parameters")
    seed: int = Field(default=42, description="Random seed")
    steps: int = Field(default=50, ge=1, description="Number of simulation steps")
    grid_size: tuple[int, int] = Field(default=(32, 32), description="Grid dimensions")


class ExperimentPlan(BaseModel):
    """Collection of planned experiments designed to test a hypothesis."""

    goal: str = Field(..., description="Overall scientific objective")
    hypothesis: Hypothesis
    planned_experiments: list[PlannedExperiment] = Field(
        default_factory=list,
        description="List of simulation runs to execute",
    )


class ExperimentFinding(BaseModel):
    """Empirical findings extracted from an executed experiment."""

    experiment_name: str
    experiment_id: str
    status: str
    key_metrics: dict[str, Any]
    interpretation: str


class ScientificReport(BaseModel):
    """Comprehensive synthesized scientific report generated by the Agent."""

    research_goal: str
    hypothesis: Hypothesis
    experiments_executed: list[ExperimentFinding]
    synthesis: str = Field(..., description="Detailed scientific analysis of findings")
    conclusion: str = Field(
        ...,
        description="Whether the hypothesis was supported, refuted, or inconclusive",
    )
    suggested_next_steps: list[str] = Field(
        default_factory=list,
        description="Follow-up experiments suggested by the findings",
    )

    def to_markdown(self) -> str:
        """Render the scientific report as a publication-ready Markdown document."""
        lines: list[str] = [
            f"# Scientific Investigation Report: {self.research_goal}",
            "",
            "## 1. Hypothesis Formulation",
            f"**Hypothesis Statement:** {self.hypothesis.statement}",
            "",
            f"**Theoretical Rationale:** {self.hypothesis.reasoning}",
            "",
            f"**Expected Outcome:** {self.hypothesis.expected_outcome}",
            "",
            "## 2. Empirical Methodology & Observables",
            "| Experiment Name | ID | Mean Density | Final Entropy | Periodic | Period |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ]

        for exp in self.experiments_executed:
            m = exp.key_metrics
            density_str = f"{m.get('mean_density', 0.0):.4f}" if "mean_density" in m else "N/A"
            entropy_str = f"{m.get('final_entropy', 0.0):.4f}" if "final_entropy" in m else "N/A"
            periodic_str = str(m.get("is_periodic", False))
            period_str = str(m.get("period", 0))
            lines.append(
                f"| {exp.experiment_name} | `{exp.experiment_id}` | "
                f"{density_str} | {entropy_str} | {periodic_str} | {period_str} |"
            )

        lines.extend([
            "",
            "### Experiment Details & Interpretations",
        ])
        for exp in self.experiments_executed:
            lines.append(f"- **{exp.experiment_name}**: {exp.interpretation}")

        lines.extend([
            "",
            "## 3. Theoretical Synthesis",
            self.synthesis,
            "",
            "## 4. Scientific Conclusion",
            f"> **{self.conclusion}**",
            "",
            "## 5. Suggested Next Steps",
        ])
        for step in self.suggested_next_steps:
            lines.append(f"- {step}")

        return "\n".join(lines)
